// Program 01: Stores roll number, grade and fee using basic C++ data types.

#include <iostream>
using namespace std;

int main() {
    int roll = 101;
    char grade = 'A';
    float fee = 12500.50f;
    cout << "Roll No: " << roll << endl;
    cout << "Grade: " << grade << endl;
    cout << "Fee: " << fee << endl;
    return 0;
}
